const test = require('node:test')
const assert = require('node:assert/strict')
const { Layout, id } = require('../engine/web/timeline-layout.js')
const lane = (type, actor, buffId = '') => ({ type, actor, buffId, id: id(type, actor, buffId) })
const a = lane('action', 'alice'), b = lane('action', 'bob')
const yin = lane('player-buff', 'alice', '98752'), rain = lane('player-buff', 'bob', '1058032')
const boss = lane('boss-buff', 'soul', '10245332'), other = lane('player-buff', 'alice', '500')
const all = [yin, rain, other, boss, a, b]
test('defaults select only the requested player effects and action tracks; bosses opt in', () => {
  const m = new Layout(); m.reconcile(all)
  assert.deepEqual(m.selected(all), [yin, rain, a, b])
  m.set(boss.id, true); m.set(boss.id, true)
  assert.deepEqual(m.selected(all), [yin, rain, a, b, boss])
})
test('mixed kinds reorder both ways, retaining unavailable tracks during partial refresh', () => {
  const m = new Layout(); m.reconcile(all); m.set(boss.id, true)
  assert.equal(m.move(boss.id, yin.id), true)
  assert.deepEqual(m.selected(all), [boss, yin, rain, a, b])
  m.move(yin.id, b.id, true)
  assert.deepEqual(m.selected([a, b, yin]), [a, b, yin])
  const reopened = new Layout(JSON.parse(JSON.stringify(m.snapshot())))
  reopened.reconcile(all)
  assert.deepEqual(reopened.selected(all), [boss, rain, a, b, yin])
  assert.equal(reopened.move('action:missing:', a.id), false)
  assert.equal(reopened.move(a.id, a.id), false)
})
test('explicitly unchecked defaults stay unchecked on refresh or restart', () => {
  const m = new Layout(); m.reconcile([a, yin]); m.set(yin.id, false)
  const restored = new Layout(JSON.parse(JSON.stringify(m.snapshot())))
  restored.reconcile(all)
  assert.deepEqual(restored.selected(all), [a, rain, b])
  restored.clear(); restored.reconcile(all)
  assert.deepEqual(restored.selected(all), [])
  const empty = new Layout(restored.snapshot()); empty.reconcile(all)
  assert.deepEqual(empty.selected(all), [])
  empty.detailPlayers = ['alice']; empty.reset(all)
  assert.deepEqual(empty.selected(all), [yin, rain, a, b])
  assert.deepEqual(empty.detailPlayers, ['alice'])
})
test('malformed preferences cannot introduce invalid lane identifiers or duplicate rows', () => {
  const m = new Layout({ version: 1, order: [null, 123, '<script>', a.id, a.id], excluded: 'wrong', detailPlayers: [null, 'bob', 'bob'] })
  assert.deepEqual(m.snapshot().order, [a.id]); assert.deepEqual(m.detailPlayers, ['bob'])
  m.set('invalid', true); assert.deepEqual(m.snapshot().order, [a.id])
  assert.deepEqual(new Layout({ version: 99, order: [boss.id] }).snapshot().order, [])
  assert.equal(new Layout(null).detailPlayers, null)
})
